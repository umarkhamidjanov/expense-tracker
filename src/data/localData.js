// Data saved in this browser by the pre-accounts version of Lumen. It is read for the
// one-time import offer and is never modified or removed unless the user confirms.
import { migrate } from './migrate'

export const LEGACY_TX_KEY = 'lumen.transactions'
export const LEGACY_SETTINGS_KEY = 'lumen.settings'
export const LOCAL_OWNER_KEY = 'lumen.local.owner'
const importKey = (userId) => `lumen.import.${userId}`

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

function readJSON(key) {
  try {
    const raw = localStorage.getItem(key)
    return raw ? JSON.parse(raw) : null
  } catch {
    return null
  }
}

// Demo transactions generated by the old app have ids like "demo-12".
export const isLegacySample = (tx) => typeof tx.id === 'string' && tx.id.startsWith('demo-')

// Local data isn't tied to an account, so on a shared browser the first account to import
// it claims it. After that, no other account is offered it, shown it, or allowed to import it.
export function getLocalOwner() {
  try {
    return localStorage.getItem(LOCAL_OWNER_KEY)
  } catch {
    return null
  }
}

export function claimLocalData(userId) {
  try {
    if (!localStorage.getItem(LOCAL_OWNER_KEY)) localStorage.setItem(LOCAL_OWNER_KEY, userId)
  } catch {
    /* ignore */
  }
}

const EMPTY = { transactions: [], own: [], sample: [], settings: null, hasData: false }

// Pass the signed-in user's id: data claimed by a different account is never returned.
export function readLocalData(forUserId) {
  const owner = getLocalOwner()
  if (owner && owner !== forUserId) return { ...EMPTY, claimedByOther: true }
  const raw = readJSON(LEGACY_TX_KEY)
  const transactions = Array.isArray(raw) ? migrate(raw).filter(isValidTx) : []
  const s = readJSON(LEGACY_SETTINGS_KEY)
  const settings = s && typeof s === 'object' ? s : null
  const own = transactions.filter((t) => !isLegacySample(t))
  const sample = transactions.filter(isLegacySample)
  return { transactions, own, sample, settings, hasData: transactions.length > 0 }
}

function isValidTx(t) {
  return (
    t &&
    (t.type === 'income' || t.type === 'expense') &&
    Number.isFinite(Number(t.amount)) &&
    Number(t.amount) > 0 &&
    typeof t.date === 'string' &&
    /^\d{4}-\d{2}-\d{2}$/.test(t.date)
  )
}

// Shape local transactions for upload. Existing UUIDs are kept so a repeated import
// doesn't create duplicates; other ids get a fresh UUID.
export function prepareForImport(txs, { sample = false } = {}) {
  return txs.map((t) => ({
    id: UUID.test(t.id) ? t.id : crypto.randomUUID(),
    type: t.type,
    name: String(t.name || '').trim().slice(0, 60) || 'Transaction',
    amount: Math.round(Number(t.amount) * 100) / 100,
    category: String(t.category || 'other').slice(0, 40),
    date: t.date,
    description: String(t.description || '').slice(0, 200),
    isSample: sample,
    createdAt: Number(t.createdAt) || Date.now(),
  }))
}

export function settingsForImport(s) {
  if (!s) return null
  const out = {}
  if (typeof s.name === 'string' && s.name.trim()) out.name = s.name.trim().slice(0, 40)
  if (typeof s.currency === 'string') out.currency = s.currency
  if (Number.isFinite(Number(s.openingBalance)) && Number(s.openingBalance) >= 0) out.openingBalance = Number(s.openingBalance)
  if (Number.isFinite(Number(s.monthlyBudget)) && Number(s.monthlyBudget) >= 0) out.monthlyBudget = Number(s.monthlyBudget)
  return Object.keys(out).length ? out : null
}

// Per-device, per-account record of how the import offer was answered.
export function getImportState(userId) {
  try {
    return localStorage.getItem(importKey(userId))
  } catch {
    return null
  }
}

export function setImportState(userId, state) {
  try {
    localStorage.setItem(importKey(userId), state)
  } catch {
    /* ignore */
  }
}

// Only called after the user explicitly confirms, and only allowed for the data's owner.
export function deleteLocalData(userId) {
  const owner = getLocalOwner()
  if (owner && owner !== userId) return false
  try {
    localStorage.removeItem(LEGACY_TX_KEY)
    // Keep the theme; drop the old settings object.
    localStorage.removeItem(LEGACY_SETTINGS_KEY)
    localStorage.removeItem(LOCAL_OWNER_KEY)
  } catch {
    /* ignore */
  }
  return true
}
